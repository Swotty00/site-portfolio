/** Lower-cases and strips everything but letters/digits and `+#.` so "Next.js", "next js" and "NEXT.JS" match. */
export function normalizeTech(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9+#.]+/g, ' ')
    .trim()
}

const BY_NAME = new Map<string, Tech>()
for (const tech of TECHS) for (const name of tech.names) BY_NAME.set(normalizeTech(name), tech)

export interface TechInfo {
  title: string
  path: string
  url: string
}

/** Icon + official website for a stack item, or `undefined` when the technology isn't in the catalogue. */
export function findTech(name: string): TechInfo | undefined {
  const tech = BY_NAME.get(normalizeTech(name))
  return tech && { title: tech.icon.title, path: tech.icon.path, url: tech.url }
}
